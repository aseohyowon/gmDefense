// 골드시스템테스트.cs
// 골드시스템로직 클래스에 대한 단위 테스트.
// GoldSystem.cs의 핵심 게임 로직(골드 추가/소비, 소환 비용 증가)을 검증한다.

using NUnit.Framework;
using GMDefense.Tests.GameLogic;

namespace GMDefense.Tests
{
    /// <summary>
    /// 골드 시스템 로직 단위 테스트 클래스.
    /// </summary>
    [TestFixture]
    public class 골드시스템테스트
    {
        // 테스트마다 새 인스턴스 사용
        private 골드시스템로직 _골드시스템 = null!;

        [SetUp]
        public void 테스트_초기화()
        {
            // 초기 골드 200, 소환 비용 100, 비용 증가량 10 으로 초기화
            _골드시스템 = new 골드시스템로직(초기골드: 200, 기본소환비용: 100, 소환비용증가량: 10);
        }

        // ────────────────────────────────────────────────
        // 골드 추가 테스트
        // ────────────────────────────────────────────────

        [Test]
        [Description("골드 추가 시 잔액이 정확히 증가한다")]
        public void 골드추가_양수입력_잔액증가()
        {
            // 준비
            int 추가전잔액 = _골드시스템.현재골드;

            // 실행
            _골드시스템.골드추가(50);

            // 검증
            Assert.That(_골드시스템.현재골드, Is.EqualTo(추가전잔액 + 50));
        }

        [Test]
        [Description("골드 추가량이 0이면 잔액이 변하지 않는다")]
        public void 골드추가_0입력_잔액불변()
        {
            int 추가전잔액 = _골드시스템.현재골드;
            _골드시스템.골드추가(0);
            Assert.That(_골드시스템.현재골드, Is.EqualTo(추가전잔액));
        }

        [Test]
        [Description("골드 추가량이 음수이면 잔액이 변하지 않는다")]
        public void 골드추가_음수입력_잔액불변()
        {
            int 추가전잔액 = _골드시스템.현재골드;
            _골드시스템.골드추가(-100);
            Assert.That(_골드시스템.현재골드, Is.EqualTo(추가전잔액));
        }

        [Test]
        [Description("골드 추가 시 이벤트가 발행된다")]
        public void 골드추가_이벤트발행확인()
        {
            int? 수신된골드 = null;
            _골드시스템.골드변경이벤트 += (골드) => 수신된골드 = 골드;

            _골드시스템.골드추가(30);

            Assert.That(수신된골드, Is.EqualTo(_골드시스템.현재골드));
        }

        // ────────────────────────────────────────────────
        // 골드 소비 테스트
        // ────────────────────────────────────────────────

        [Test]
        [Description("골드가 충분할 때 소비 성공하고 잔액이 감소한다")]
        public void 골드소비_충분한잔액_성공()
        {
            // 준비: 초기 잔액 200, 100 소비
            bool 결과 = _골드시스템.골드소비(100);

            Assert.That(결과, Is.True);
            Assert.That(_골드시스템.현재골드, Is.EqualTo(100));
        }

        [Test]
        [Description("골드가 부족할 때 소비 실패하고 잔액이 변하지 않는다")]
        public void 골드소비_잔액부족_실패()
        {
            bool 결과 = _골드시스템.골드소비(300); // 잔액 200, 300 소비 시도

            Assert.That(결과, Is.False);
            Assert.That(_골드시스템.현재골드, Is.EqualTo(200)); // 잔액 변화 없음
        }

        [Test]
        [Description("정확히 잔액과 같은 금액을 소비할 수 있다")]
        public void 골드소비_정확한잔액_성공()
        {
            bool 결과 = _골드시스템.골드소비(200); // 잔액과 정확히 동일

            Assert.That(결과, Is.True);
            Assert.That(_골드시스템.현재골드, Is.EqualTo(0));
        }

        [Test]
        [Description("0 골드 소비는 실패 처리된다")]
        public void 골드소비_0입력_실패()
        {
            bool 결과 = _골드시스템.골드소비(0);

            Assert.That(결과, Is.False);
        }

        // ────────────────────────────────────────────────
        // 소환 비용 증가 테스트
        // ────────────────────────────────────────────────

        [Test]
        [Description("첫 소환 비용은 기본 소환 비용(100)이다")]
        public void 소환비용_초기값_기본비용()
        {
            Assert.That(_골드시스템.현재소환비용, Is.EqualTo(100));
        }

        [Test]
        [Description("소환 비용 지불 후 다음 소환 비용이 비용증가량(10)만큼 오른다")]
        public void 소환비용지불_한번_비용증가()
        {
            _골드시스템.소환비용지불();

            // 기본 100 + 1회 × 10 = 110
            Assert.That(_골드시스템.현재소환비용, Is.EqualTo(110));
        }

        [Test]
        [Description("소환 3회 후 비용이 130이 된다")]
        public void 소환비용지불_세번_비용증가()
        {
            _골드시스템.골드추가(1000); // 골드 충분하게 보충

            _골드시스템.소환비용지불(); // 100, 다음 110
            _골드시스템.소환비용지불(); // 110, 다음 120
            _골드시스템.소환비용지불(); // 120, 다음 130

            Assert.That(_골드시스템.현재소환비용, Is.EqualTo(130));
        }

        [Test]
        [Description("골드 부족 시 소환 비용 지불 실패하고 비용이 오르지 않는다")]
        public void 소환비용지불_골드부족_실패()
        {
            // 잔액을 50으로 줄임 (소환 비용 100보다 적음)
            _골드시스템 = new 골드시스템로직(초기골드: 50, 기본소환비용: 100, 소환비용증가량: 10);

            bool 결과 = _골드시스템.소환비용지불();

            Assert.That(결과, Is.False);
            Assert.That(_골드시스템.현재소환비용, Is.EqualTo(100)); // 비용 변화 없음
            Assert.That(_골드시스템.소환횟수, Is.EqualTo(0));        // 횟수 변화 없음
        }

        [Test]
        [Description("소환 성공 시 소환 횟수가 1 증가한다")]
        public void 소환비용지불_성공_횟수증가()
        {
            _골드시스템.소환비용지불();
            Assert.That(_골드시스템.소환횟수, Is.EqualTo(1));
        }

        // ────────────────────────────────────────────────
        // 골드 충분 여부 확인 테스트
        // ────────────────────────────────────────────────

        [Test]
        [Description("잔액이 필요 골드 이상이면 골드충분이 true를 반환한다")]
        public void 골드충분_충분한잔액_참()
        {
            Assert.That(_골드시스템.골드충분(200), Is.True);
            Assert.That(_골드시스템.골드충분(100), Is.True);
        }

        [Test]
        [Description("잔액이 필요 골드 미만이면 골드충분이 false를 반환한다")]
        public void 골드충분_부족한잔액_거짓()
        {
            Assert.That(_골드시스템.골드충분(201), Is.False);
        }
    }
}
