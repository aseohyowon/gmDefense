// 시너지테스트.cs
// 시너지로직 클래스에 대한 단위 테스트.
// TraitSystem.cs의 시너지 카운팅 및 배율 계산 로직을 검증한다.

using NUnit.Framework;
using GMDefense.Tests.GameLogic;

namespace GMDefense.Tests
{
    /// <summary>
    /// 특성 시너지 로직 단위 테스트 클래스.
    /// </summary>
    [TestFixture]
    public class 시너지테스트
    {
        // ────────────────────────────────────────────────
        // 시너지 카운팅 테스트
        // ────────────────────────────────────────────────

        [Test]
        [Description("영웅이 없을 때 시너지 카운트는 0이다")]
        public void 시너지재계산_영웅없음_카운트0()
        {
            var 시너지 = new 시너지로직();
            시너지.시너지재계산(Array.Empty<특성종류[]>());

            Assert.That(시너지.활성시너지목록, Is.Empty);
        }

        [Test]
        [Description("없음 특성은 시너지 카운트에 포함되지 않는다")]
        public void 시너지재계산_없음특성_카운트제외()
        {
            var 시너지 = new 시너지로직();
            시너지.시너지재계산(new[] { new[] { 특성종류.없음 } });

            Assert.That(시너지.활성시너지목록, Is.Empty);
        }

        [Test]
        [Description("빛의수호자 특성 영웅 1명 배치 시 카운트가 1이다")]
        public void 시너지재계산_빛의수호자1명_카운트1()
        {
            var 시너지 = new 시너지로직();
            시너지.시너지재계산(new[] { new[] { 특성종류.빛의수호자 } });

            Assert.That(시너지.특성영웅수가져오기(특성종류.빛의수호자), Is.EqualTo(1));
        }

        [Test]
        [Description("빛의수호자 특성 영웅 3명 배치 시 카운트가 3이다")]
        public void 시너지재계산_빛의수호자3명_카운트3()
        {
            var 시너지 = new 시너지로직();
            시너지.시너지재계산(new[]
            {
                new[] { 특성종류.빛의수호자 },
                new[] { 특성종류.빛의수호자 },
                new[] { 특성종류.빛의수호자 }
            });

            Assert.That(시너지.특성영웅수가져오기(특성종류.빛의수호자), Is.EqualTo(3));
        }

        [Test]
        [Description("한 영웅이 두 가지 특성을 보유하면 각각 카운트된다")]
        public void 시너지재계산_복수특성영웅_각특성카운트()
        {
            var 시너지 = new 시너지로직();
            // 한 영웅이 빛의수호자 + 불꽃전사 두 가지 특성 보유
            시너지.시너지재계산(new[] { new[] { 특성종류.빛의수호자, 특성종류.불꽃전사 } });

            Assert.That(시너지.특성영웅수가져오기(특성종류.빛의수호자), Is.EqualTo(1));
            Assert.That(시너지.특성영웅수가져오기(특성종류.불꽃전사), Is.EqualTo(1));
        }

        [Test]
        [Description("재계산 시 이전 결과가 초기화된다")]
        public void 시너지재계산_두번실행_이전결과초기화()
        {
            var 시너지 = new 시너지로직();

            // 첫 번째: 빛의수호자 2명
            시너지.시너지재계산(new[]
            {
                new[] { 특성종류.빛의수호자 },
                new[] { 특성종류.빛의수호자 }
            });
            Assert.That(시너지.특성영웅수가져오기(특성종류.빛의수호자), Is.EqualTo(2));

            // 두 번째: 불꽃전사 1명만 (빛의수호자 없음)
            시너지.시너지재계산(new[] { new[] { 특성종류.불꽃전사 } });

            Assert.That(시너지.특성영웅수가져오기(특성종류.빛의수호자), Is.EqualTo(0),
                "재계산 후 빛의수호자 카운트는 0이어야 한다");
            Assert.That(시너지.특성영웅수가져오기(특성종류.불꽃전사), Is.EqualTo(1));
        }

        // ────────────────────────────────────────────────
        // 공격력 배율 계산 테스트
        // ────────────────────────────────────────────────

        [Test]
        [Description("시너지 설정이 없으면 공격력 배율은 1.0이다")]
        public void 전체공격력배율_설정없음_배율1()
        {
            var 시너지 = new 시너지로직();
            시너지.시너지재계산(new[] { new[] { 특성종류.빛의수호자, 특성종류.빛의수호자 } });

            Assert.That(시너지.전체공격력배율가져오기(), Is.EqualTo(1f));
        }

        [Test]
        [Description("빛의수호자 2명 배치 시 공격력 배율이 1.5배가 된다")]
        public void 전체공격력배율_빛의수호자2명_1점5배()
        {
            // 설정: 빛의수호자 2명 이상 시 공격력 1.5배
            var 설정 = new List<특성시너지설정>
            {
                new 특성시너지설정
                {
                    특성 = 특성종류.빛의수호자,
                    단계목록 = new List<시너지단계데이터>
                    {
                        new 시너지단계데이터 { 필요영웅수 = 2, 공격력배율 = 1.5f, 공격속도배율 = 1f }
                    }
                }
            };
            var 시너지 = new 시너지로직(설정);

            시너지.시너지재계산(new[]
            {
                new[] { 특성종류.빛의수호자 },
                new[] { 특성종류.빛의수호자 }
            });

            Assert.That(시너지.전체공격력배율가져오기(), Is.EqualTo(1.5f).Within(0.001f));
        }

        [Test]
        [Description("영웅 수가 발동 조건 미만이면 배율은 1.0이다")]
        public void 전체공격력배율_조건미만_배율1()
        {
            // 설정: 빛의수호자 2명 이상 시만 발동
            var 설정 = new List<특성시너지설정>
            {
                new 특성시너지설정
                {
                    특성 = 특성종류.빛의수호자,
                    단계목록 = new List<시너지단계데이터>
                    {
                        new 시너지단계데이터 { 필요영웅수 = 2, 공격력배율 = 1.5f, 공격속도배율 = 1f }
                    }
                }
            };
            var 시너지 = new 시너지로직(설정);

            // 빛의수호자 1명만 (발동 조건 2명 미만)
            시너지.시너지재계산(new[] { new[] { 특성종류.빛의수호자 } });

            Assert.That(시너지.전체공격력배율가져오기(), Is.EqualTo(1f));
        }

        // ────────────────────────────────────────────────
        // 공격속도 배율 계산 테스트
        // ────────────────────────────────────────────────

        [Test]
        [Description("어둠의사냥꾼 3명 배치 시 공격속도 배율이 1.3배가 된다")]
        public void 전체공격속도배율_어둠의사냥꾼3명_1점3배()
        {
            var 설정 = new List<특성시너지설정>
            {
                new 특성시너지설정
                {
                    특성 = 특성종류.어둠의사냥꾼,
                    단계목록 = new List<시너지단계데이터>
                    {
                        new 시너지단계데이터 { 필요영웅수 = 3, 공격력배율 = 1f, 공격속도배율 = 1.3f }
                    }
                }
            };
            var 시너지 = new 시너지로직(설정);

            시너지.시너지재계산(new[]
            {
                new[] { 특성종류.어둠의사냥꾼 },
                new[] { 특성종류.어둠의사냥꾼 },
                new[] { 특성종류.어둠의사냥꾼 }
            });

            Assert.That(시너지.전체공격속도배율가져오기(), Is.EqualTo(1.3f).Within(0.001f));
        }

        [Test]
        [Description("두 가지 특성 시너지가 동시에 발동되면 공격력 배율이 곱해진다")]
        public void 전체공격력배율_두시너지동시발동_배율곱()
        {
            // 설정: 빛의수호자 2명 = ×1.5, 불꽃전사 2명 = ×1.2
            var 설정 = new List<특성시너지설정>
            {
                new 특성시너지설정
                {
                    특성 = 특성종류.빛의수호자,
                    단계목록 = new List<시너지단계데이터>
                    {
                        new 시너지단계데이터 { 필요영웅수 = 2, 공격력배율 = 1.5f, 공격속도배율 = 1f }
                    }
                },
                new 특성시너지설정
                {
                    특성 = 특성종류.불꽃전사,
                    단계목록 = new List<시너지단계데이터>
                    {
                        new 시너지단계데이터 { 필요영웅수 = 2, 공격력배율 = 1.2f, 공격속도배율 = 1f }
                    }
                }
            };
            var 시너지 = new 시너지로직(설정);

            시너지.시너지재계산(new[]
            {
                new[] { 특성종류.빛의수호자 },
                new[] { 특성종류.빛의수호자 },
                new[] { 특성종류.불꽃전사 },
                new[] { 특성종류.불꽃전사 }
            });

            // 1.5 × 1.2 = 1.8
            Assert.That(시너지.전체공격력배율가져오기(), Is.EqualTo(1.8f).Within(0.001f));
        }
    }
